#include <stdio.h>
#include <sys/types.h>
#include <sys/wait.h>
#include <unistd.h>
#include <stdlib.h>
#include <signal.h>
#define OK 1
// Made by : Diego Palomino Barrientos
int main(int argc,char *argv[]){

    if(argc != 2){
        printf("Use chainpids #process \n");
        exit(OK);
    }

    int n = atoi(argv[1]);

    pid_t root = getpid(),child;
    int pipes[n+1][2];
    int index;
    for(int i=0;i<n+1;i++){
        pipe(pipes[i]);
    }
    for(int i=0;i<n+1;i++){
        write(pipes[i][1],&root,sizeof(pid_t));
    }
    index = 0;
    for(int i=0;i<n;i++){
        if(!(child = fork())){
            //child write
            index = i+1; 
            pid_t pid = getpid();
            for(int j=0;j<n+1;j++){
                write(pipes[j][1],&pid,sizeof(pid_t));
            }
        }
        else break;
    }    
    //every close write
    for(int i=0;i<n+1;i++){
       close(pipes[i][1]); 
    }

    wait(NULL);
    pid_t pid;
    printf("--------------------------\n");
    while(read(pipes[index][0],&pid,sizeof(pid_t)) != 0){
        printf("    %d    %d\n",(int)getpid(),(int)pid);
    }
    printf("--------------------------\n");

    for(int i=0;i<n+1;i++){
        close(pipes[i][0]);
    }
    return 0;
}

